// Runs the labelled evaluation set through the deployed app (the Forge LLM is only reachable
// inside Forge) in small slices, then writes eval/results.json, eval/results.md and
// src/data/eval-results.js (shown on the register page).
//
//   EVAL_URL=<web trigger url> EVAL_TOKEN=<token> npm run eval

import fs from 'node:fs';
import { EVAL_CASES } from '../src/data/eval-cases.js';
import { HOLDOUT_CASES } from '../src/data/eval-holdout.js';
import { scoreRows } from '../src/core/evaluate.js';

const { EVAL_URL, EVAL_TOKEN } = process.env;
const MODEL = process.env.EVAL_MODEL || 'claude-sonnet-4-6';
if (!EVAL_URL || !EVAL_TOKEN) {
  console.error('Set EVAL_URL (forge webtrigger create -f eval-webtrigger) and EVAL_TOKEN.');
  process.exit(1);
}

const SET = process.env.EVAL_SET === 'holdout' ? 'holdout' : 'dev';
const CASES = SET === 'holdout' ? HOLDOUT_CASES : EVAL_CASES;
const suffix = SET === 'holdout' ? '-holdout' : '';
const STEP = 2;
const rows = [];
for (let from = 0; from < CASES.length; from += STEP) {
  const url = `${EVAL_URL}?token=${encodeURIComponent(EVAL_TOKEN)}&from=${from}&to=${from + STEP}&set=${SET}`;
  let report;
  for (let attempt = 1; attempt <= 3 && !report; attempt++) {
    const res = await fetch(url);
    if (res.ok) report = await res.json();
    else console.error(`slice ${from}: HTTP ${res.status}, attempt ${attempt}`);
  }
  if (!report) throw new Error(`slice ${from} failed`);
  for (const r of report.details) {
    rows.push(r);
    const ok = [...r.expected].sort().join() === [...r.got].sort().join();
    console.log(`${ok ? 'ok  ' : 'MISS'} ${r.id} expected=[${r.expected}] got=[${r.got}]${r.rejected.length ? ` rejected=${r.rejected.length}` : ''}`);
  }
}

const summary = { ...scoreRows(rows), date: new Date().toISOString().slice(0, 10), model: MODEL };
fs.writeFileSync(new URL(`./results${suffix}.json`, import.meta.url), JSON.stringify({ ...summary, details: rows }, null, 2) + '\n');

const pct = (x) => `${Math.round(x * 100)}%`;
const line = (label, r) => `| ${label} | ${pct(r.conflict.precision)} (${r.conflict.tp}/${r.conflict.tp + r.conflict.fp}) | ${pct(r.conflict.recall)} (${r.conflict.tp}/${r.conflict.tp + r.conflict.fn}) | ${pct(r.revisit.precision)} | ${pct(r.revisit.recall)} | ${r.falseAlarms.alarmed} of ${r.falseAlarms.cases} |`;
const md = `# Evaluation results (${SET === 'holdout' ? 'held-out set, run once, no tuning' : 'development set'})

${summary.cases} labelled work items against the ${'Kestrel'} sample decisions, ${summary.date}, model ${MODEL}.

| | Conflict precision | Conflict recall | Revisit precision | Revisit recall | False alarms on items that should stay quiet |
|---|---|---|---|---|---|
${line('With quote verification (shipped)', summary.withVerification)}
${line('Without verification', summary.withoutVerification)}

Exact-match accuracy by group (all expected findings and nothing else):

| Group | Correct |
|---|---|
${Object.entries(summary.byGroup).map(([g, v]) => `| ${g} | ${v.correct} of ${v.cases} |`).join('\n')}

Per-case results are in [results${suffix}.json](results${suffix}.json). Cases are in [src/data/eval-cases.js](../src/data/eval-cases.js).
`;
fs.writeFileSync(new URL(`./results${suffix}.md`, import.meta.url), md);
// Merge into the bundled UI summary (keeps the other set's numbers).
const uiFile = new URL('../src/data/eval-results.js', import.meta.url);
let ui = {};
try { ui = (await import(uiFile.href + `?t=${Date.now()}`)).EVAL_RESULTS || {}; } catch { ui = {}; }
if (ui && ui.cases) ui = {}; // old single-set format
ui[SET] = summary;
fs.writeFileSync(uiFile, `// Generated by eval/run.js. Shown on the register page's Accuracy tab.\nexport const EVAL_RESULTS = ${JSON.stringify(ui, null, 2)};\n`);
console.log(md);
